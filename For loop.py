# This program prints even numbers from 0 to 100 using a for loop
print("Even numbers from 0 to 100:")
for i in range(0, 101, 2):
    print(i)

# This program prints odd numbers from 1 to 100 using a for loop
print("Odd numbers from 1 to 100:")
for i in range(1, 101, 2):
    print(i)

# This program prints the multiples of 3 from 0 to 100 using a for loop
print("Multiples of 3 from 0 to 100:")
for i in range(0,101,3):
    print(i)